// writeTempConfig writes a single profile to a temp config file and returns its
// path. setDefault controls whether it becomes the default profile.
func writeTempConfig(t *testing.T, profile string, env map[string]string, comments map[string]string, setDefault bool) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "config.yaml")
	if err := config.UpsertProfile(path, profile, config.Profile{Env: env}, setDefault, false, comments); err != nil {
		t.Fatalf("UpsertProfile: %v", err)
	}
	return path
}

// withGlobalConfig sets globalFlags to point at path with local layering off,
// restoring the previous values on cleanup.
func withGlobalConfig(t *testing.T, path string) {
	t.Helper()
	savedConfig, savedNoLocal := globalFlags.configPath, globalFlags.noLocal
	globalFlags.configPath = path
	globalFlags.noLocal = true
	t.Cleanup(func() {
		globalFlags.configPath = savedConfig
		globalFlags.noLocal = savedNoLocal
	})
}

func TestRunDotenvStdout(t *testing.T) {
	path := writeTempConfig(t, "prod",
		map[string]string{"DB_HOST": "db.example.com", "API_TOKEN": "sk-live"},
		map[string]string{"DB_HOST": "Primary database host"}, true)
	withGlobalConfig(t, path)

	var out bytes.Buffer
	// Empty profile falls back to the default ("prod"); outPath "" → stdout; no confirm.
	if err := runDotenv(&out, "", "", false, false, nil); err != nil {
		t.Fatalf("runDotenv: %v", err)
	}
	s := out.String()
	if !strings.Contains(s, "# Generated by enver from profile \"prod\"") {
		t.Errorf("missing header:\n%s", s)
	}
	if !strings.Contains(s, "# Primary database host\nDB_HOST=db.example.com") {
		t.Errorf("missing commented var:\n%s", s)
	}
	if !strings.Contains(s, "API_TOKEN=sk-live") {
		t.Errorf("missing unmasked value:\n%s", s)
	}
	// Keys sorted alphabetically: API_TOKEN precedes DB_HOST.
	if ia, ib := strings.Index(s, "API_TOKEN="), strings.Index(s, "DB_HOST="); ia < 0 || ib < 0 || ia > ib {
		t.Errorf("keys not sorted:\n%s", s)
	}
}

