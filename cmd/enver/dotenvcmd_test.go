func TestWriteDotenvFileCreatesWith0600(t *testing.T) {
	path := filepath.Join(t.TempDir(), "out.env")
	var out bytes.Buffer
	if err := writeDotenvFile(&out, path, []byte("FOO=bar\n"), false, nil, 1); err != nil {
		t.Fatalf("writeDotenvFile: %v", err)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}
	if perm := info.Mode().Perm(); perm != 0o600 {
		t.Errorf("file mode = %o, want 0600", perm)
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != "FOO=bar\n" {
		t.Errorf("file contents = %q, err %v", string(got), err)
	}
	if !strings.Contains(out.String(), "✓ wrote out.env (1 vars)") {
		t.Errorf("missing confirmation line:\n%s", out.String())
	}
}

func TestWriteDotenvFileOverwriteConfirmed(t *testing.T) {
	path := filepath.Join(t.TempDir(), "e.env")
	if err := os.WriteFile(path, []byte("OLD=1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	called := false
	confirm := func(msg string, def bool) (bool, error) {
		called = true
		if !strings.Contains(msg, "Overwrite") {
			t.Errorf("confirm prompt = %q, want Overwrite", msg)
		}
		return true, nil
	}
	if err := writeDotenvFile(&out, path, []byte("NEW=2\n"), false, confirm, 1); err != nil {
		t.Fatalf("writeDotenvFile: %v", err)
	}
	if !called {
		t.Error("confirm was not called for existing file")
	}
	got, _ := os.ReadFile(path)
	if !strings.Contains(string(got), "NEW=2") {
		t.Errorf("file not overwritten:\n%s", string(got))
	}
}

func TestWriteDotenvFileOverwriteRefused(t *testing.T) {
	path := filepath.Join(t.TempDir(), "e.env")
	if err := os.WriteFile(path, []byte("OLD=1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	refuse := func(string, bool) (bool, error) { return false, nil }
	if err := writeDotenvFile(&out, path, []byte("NEW=2\n"), false, refuse, 1); err != nil {
		t.Fatalf("refuse should not error: %v", err)
	}
	got, _ := os.ReadFile(path)
	if string(got) != "OLD=1\n" {
		t.Errorf("file overwritten after refuse:\n%s", string(got))
	}
	if !strings.Contains(out.String(), "aborted") {
		t.Errorf("declined overwrite should print aborted:\n%s", out.String())
	}
	if strings.Contains(out.String(), "✓ wrote") {
		t.Error("confirmation printed after refuse")
	}
}

func TestWriteDotenvFileOverwriteNonInteractive(t *testing.T) {
	path := filepath.Join(t.TempDir(), "e.env")
	if err := os.WriteFile(path, []byte("OLD=1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	broken := func(string, bool) (bool, error) { return false, io.EOF }
	err := writeDotenvFile(&out, path, []byte("NEW=2\n"), false, broken, 1)
	if err == nil || !strings.Contains(err.Error(), "force") {
		t.Fatalf("non-interactive refusal should error with --force hint, got: %v", err)
	}
	got, _ := os.ReadFile(path)
	if string(got) != "OLD=1\n" {
		t.Errorf("file changed after non-interactive refusal:\n%s", string(got))
	}
	if strings.Contains(out.String(), "✓ wrote") {
		t.Error("confirmation printed after failed prompt")
	}
}

func TestWriteDotenvFileForceSkipsConfirm(t *testing.T) {
	path := filepath.Join(t.TempDir(), "e.env")
	if err := os.WriteFile(path, []byte("OLD=1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	called := false
	never := func(string, bool) (bool, error) { called = true; return false, nil }
	if err := writeDotenvFile(&out, path, []byte("NEW=2\n"), true, never, 1); err != nil {
		t.Fatalf("writeDotenvFile: %v", err)
	}
	if called {
		t.Error("confirm called under --force")
	}
	got, _ := os.ReadFile(path)
	if !strings.Contains(string(got), "NEW=2") {
		t.Errorf("file not force-overwritten:\n%s", string(got))
	}
}

func TestWriteDotenvFileEnforces0600OnOverwrite(t *testing.T) {
	path := filepath.Join(t.TempDir(), "e.env")
	if err := os.WriteFile(path, []byte("OLD=1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	if err := writeDotenvFile(&out, path, []byte("NEW=2\n"), true, nil, 1); err != nil {
		t.Fatalf("writeDotenvFile: %v", err)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}
	if perm := info.Mode().Perm(); perm != 0o600 {
		t.Errorf("file mode after overwrite = %o, want 0o600", perm)
	}
}

func TestRunDotenvDoesNotExpand(t *testing.T) {
	path := writeTempConfig(t, "p", map[string]string{"URL": "$HOST/x"}, nil, true)
	withGlobalConfig(t, path)
	t.Setenv("HOST", "h")
	var out bytes.Buffer
	if err := runDotenv(&out, "", "", false, false, nil); err != nil {
		t.Fatalf("runDotenv: %v", err)
	}
	if !strings.Contains(out.String(), "$HOST/x") || strings.Contains(out.String(), "h/x") {
		t.Errorf("dotenv should not expand $HOST; got:\n%s", out.String())
	}
}
