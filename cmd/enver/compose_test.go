// completeCmd builds the bare completion command the completeProfile tests
// use, with the flags completeProfile reads pointed at the fixture.
func completeCmd(t *testing.T, path string) *cobra.Command {
	t.Helper()
	cmd := &cobra.Command{}
	cmd.Flags().String("config", "", "")
	cmd.Flags().Bool("no-local", false, "")
	_ = cmd.Flags().Set("config", path)
	return cmd
}

// composeConfig writes the composition fixture: a base profile plus two
// model-slot profiles, one of which overrides the base endpoint.
func composeConfig(t *testing.T) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "config.yaml")
	body := "profiles:\n" +
		"  base:\n    env:\n      ENDPOINT: from-base\n" +
		"  slotA:\n    env:\n      ENDPOINT: from-a\n      ONLY_A: a\n" +
		"  slotB:\n    env:\n      ONLY_B: b\n"
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write config: %v", err)
	}
	return path
}

// runRoot runs rootCmd with args, capturing stdout. It resets args and the
// out writer on cleanup so later tests start from a clean command state.
func runRoot(t *testing.T, args ...string) string {
	t.Helper()
	var out bytes.Buffer
	rootCmd.SetArgs(args)
	rootCmd.SetOut(&out)
	t.Cleanup(func() {
		rootCmd.SetArgs(nil)
		rootCmd.SetOut(nil)
		showFormat = "text"
		exportFormat = "bash"
	})
	if err := rootCmd.Execute(); err != nil {
		t.Fatalf("%v: %v", args, err)
	}
	return out.String()
}

func TestShowComposesProfiles(t *testing.T) {
	withGlobalConfig(t, composeConfig(t))

	s := runRoot(t, "show", "base", "slotA")
	if !strings.Contains(s, "ENDPOINT=from-a") {
		t.Fatalf("show must prefer the later profile's value:\n%s", s)
	}
	if !strings.Contains(s, "ONLY_A=a") {
		t.Fatalf("show must keep the union of members' keys:\n%s", s)
	}
	if !strings.Contains(s, "# profile: base → slotA") {
		t.Fatalf("show must render the composed chain:\n%s", s)
	}
}

func TestShowJSONComposedLabel(t *testing.T) {
	withGlobalConfig(t, composeConfig(t))

	s := runRoot(t, "show", "base", "slotA", "--format", "json")
	var doc showJSON
	if err := json.Unmarshal([]byte(s), &doc); err != nil {
		t.Fatalf("json: %v\n%s", err, s)
	}
	if doc.Profile != "base+slotA" {
		t.Fatalf("profile label = %q, want base+slotA", doc.Profile)
	}
	if got := doc.Env["ENDPOINT"]; got != "from-a" {
		t.Fatalf("ENDPOINT = %q, want from-a", got)
	}
	if len(doc.Chain) != 2 || doc.Chain[0] != "base" || doc.Chain[1] != "slotA" {
		t.Fatalf("chain = %v, want [base slotA]", doc.Chain)
	}
}

