func TestRunDotenvComposesProfiles(t *testing.T) {
	withGlobalConfig(t, composeConfig(t))

	var out bytes.Buffer
	if err := runDotenv(&out, []string{"base", "slotA"}, "", false, false, nil); err != nil {
		t.Fatalf("runDotenv: %v", err)
	}
	s := out.String()
	if !strings.Contains(s, `# Generated by enver from profile "base+slotA"`) {
		t.Fatalf("missing composed header, want base+slotA:\n%s", s)
	}
	if !strings.Contains(s, "ENDPOINT=from-a") {
		t.Fatalf("dotenv must prefer the later profile's value:\n%s", s)
	}
}

func TestCompleteProfileOnEveryPosition(t *testing.T) {
	path := composeConfig(t)
	cmd := completeCmd(t, path)

	got, directive := completeProfile(cmd, []string{"base"}, "")
	if directive != cobra.ShellCompDirectiveNoFileComp {
		t.Fatalf("directive = %v, want NoFileComp", directive)
	}
	for _, want := range []string{"slotA", "slotB"} {
		if !containsToken(got, want) {
			t.Fatalf("second position must still offer profiles, got %v", got)
		}
	}
	if containsToken(got, "base") {
		t.Fatalf("already typed profiles must leave the candidates, got %v", got)
	}
}

func TestCompleteProfileAfterDashFallsToFileCompletion(t *testing.T) {
	path := composeConfig(t)
	cmd := completeCmd(t, path)
	// Fake the raw __complete line `enver x base slotA -- <TAB>`: the cursor
	// sits after the dash, so the child command owns the completion.
	prev := osArgs
	osArgs = []string{"enver", "__complete", "x", "base", "slotA", "--", ""}
	t.Cleanup(func() { osArgs = prev })

	got, directive := completeProfile(cmd, []string{"base", "slotA"}, "")
	if directive != cobra.ShellCompDirectiveDefault {
		t.Fatalf("directive = %v, want Default (file completion) after --", directive)
	}
	if len(got) != 0 {
		t.Fatalf("candidates = %v, want none after --", got)
	}
}

// containsToken reports whether the completion candidate list includes token.
func containsToken(candidates []string, token string) bool {
	for _, c := range candidates {
		if c == token {
			return true
		}
	}
	return false
}
