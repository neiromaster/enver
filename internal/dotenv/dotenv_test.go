// TestFormatRoundTrip asserts the future import can recover each value: strip
// the optional surrounding single quotes from the rendered value.
func TestFormatRoundTrip(t *testing.T) {
	env := map[string]string{"PLAIN": "x", "SPACED": "a b", "HASH": "a#b"}
	out := string(Format(env, nil, Options{Header: false}))
	for _, line := range strings.Split(strings.TrimRight(out, "\n"), "\n") {
		parts := strings.SplitN(line, "=", 2)
		key, val := parts[0], parts[1]
		if len(val) >= 2 && val[0] == '\'' && val[len(val)-1] == '\'' {
			val = val[1 : len(val)-1]
		}
		if val != env[key] {
			t.Errorf("round-trip %s: got %q, want %q", key, val, env[key])
		}
	}
}

func TestFormatExpansionBridge(t *testing.T) {
	// $-values double-quoted: $$ -> \$, $VAR left intact; no-$ value stays bare/quoted.
	got := string(Format(
		map[string]string{
			"URL":   "postgres://$HOST/db",
			"COST":  "price$$5",
			"MIX":   "$A and $$B",
			"PLAIN": "hello",
		},
		nil, Options{Header: false},
	))
	want := "COST=\"price\\$5\"\n" +
		"MIX=\"$A and \\$B\"\n" +
		"PLAIN=hello\n" +
		"URL=\"postgres://$HOST/db\"\n"
	if got != want {
		t.Errorf("Format bridge:\ngot:  %q\nwant: %q", got, want)
	}
}

func TestFormatRoundTripThroughParse(t *testing.T) {
	env := map[string]string{"URL": "postgres://$HOST/db", "COST": "price$$5", "PLAIN": "hi"}
	out := Format(env, nil, Options{Header: false})
	got, err := Parse(out)
	if err != nil {
		t.Fatal(err)
	}
	back := map[string]string{}
	for _, e := range got {
		back[e.Key] = e.Value
	}
	for k, v := range env {
		if back[k] != v {
			t.Errorf("round-trip %s: got %q, want %q", k, back[k], v)
		}
	}
}
