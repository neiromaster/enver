func TestNeedsQuote(t *testing.T) {
	cases := []struct {
		in   string
		want bool
	}{
		{"", true}, // empty
		{"plain", false},
		{"db.example.com", false},
		{"sk-live-xxxx", false},
		{"a/b:c@d", false},
		{"redis://localhost:6379", false},
		{"has space", true},
		{"tab\there", true},
		{"new\nline", true},
		{"has#hash", true},
		{"key=val", true},
		{"dollar$var", true},
		{"single'quote", true},
		{"double\"quote", true},
		{"back\\slash", true},
		{"tick`here", true},
		{"lead space", true},
		{"trail space ", true},
		{"del\x7fchar", true},
	}
	for _, c := range cases {
		if got := needsQuote(c.in); got != c.want {
			t.Errorf("needsQuote(%q) = %v, want %v", c.in, got, c.want)
		}
	}
}

func TestQuote(t *testing.T) {
	cases := []struct {
		in, want string
	}{
		{"plain", "'plain'"},
		{"", "''"},
		{"has space", "'has space'"},
		// "it's" -> wrap, and replace the embedded ' with '\''  =>  'it'\''s'
		{"it's", "'it'\\''s'"},
		{"a'b'c", "'a'\\''b'\\''c'"},
		{"dollar$5", "'dollar$5'"},
	}
	for _, c := range cases {
		if got := quote(c.in); got != c.want {
			t.Errorf("quote(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

func TestFormatPlain(t *testing.T) {
	got := string(Format(
		map[string]string{"DB_HOST": "db.example.com", "API_TOKEN": "sk-live"},
		nil,
		Options{Header: false},
	))
	want := "API_TOKEN=sk-live\nDB_HOST=db.example.com\n"
	if got != want {
		t.Errorf("Format plain:\ngot:  %q\nwant: %q", got, want)
	}
}

